@dataclass(frozen=True)
class DurationBand:
    """One duration class and the range that puts an asset in it.

    Bounds are seconds, lower-inclusive and upper-exclusive, so an asset of
    exactly 2.0 s lands in SHORT rather than in both or neither.
    """

    name: str
    min_seconds: float
    max_seconds: float | None


# §9's suggested defaults. Configurable: `config.py` can replace the table, and
# the exact duration is always stored alongside the class so no consumer is ever
# forced to work from the bucket alone.
DEFAULT_DURATION_BANDS: tuple[DurationBand, ...] = (
    DurationBand("MICRO", 0.0, 2.0),
    DurationBand("SHORT", 2.0, 6.0),
    DurationBand("MEDIUM", 6.0, 20.0),
    DurationBand("LONG", 20.0, 60.0),
    DurationBand("EXTENDED", 60.0, None),
)


def duration_class(seconds: float, bands: tuple[DurationBand, ...] = DEFAULT_DURATION_BANDS) -> str:
    for band in bands:
        if seconds >= band.min_seconds and (band.max_seconds is None or seconds < band.max_seconds):
            return band.name
    return bands[-1].name


