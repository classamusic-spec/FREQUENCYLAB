"""Canonical schema for the organic audio asset manifest.

This module is the contract. The analysis code, the override merge, the
validator, the report and the generated TypeScript types are all derived from
what is declared here, so there is exactly one definition of what an asset
record is (§25: no duplicate competing schemas).

Three version numbers travel with every manifest, because they answer different
questions and move independently (§33):

  ``ANALYSIS_VERSION``   what the measuring code does. Bumping it invalidates
                         the analysis cache and forces every asset to be
                         re-measured, so it must change whenever a number this
                         pipeline computes would come out differently.
  ``SCHEMA_VERSION``     the shape of the record. A consumer that understands
                         schema 1 can refuse a schema 2 manifest outright
                         rather than reading fields that have moved.
  ``LIBRARY_VERSION``    the content of the sample library itself, which is a
                         curatorial fact rather than a technical one (§34).
                         Protocol DNA will reference it, so it is declared here
                         and carried through rather than derived.
"""

